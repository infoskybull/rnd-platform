// Get navigation items based on role and active path
export const getNavigationItems = (
  role: "creator" | "publisher" | "admin" | undefined,
  activePath?: string
): NavigationItem[] => {
  const baseItems: NavigationItem[] = [
    {
      label: "Dashboard",
      path: "/dashboard",
      icon: dashboardIcon,
    },
  ];

  // Add role-specific items
  if (role === "publisher") {
    baseItems.push({
      label: "Marketplace",
      path: "/marketplace",
      icon: marketplaceIcon,
    });
  } else if (role === "creator") {
    baseItems.push({
      label: "Use A.I",
      path: "/prototype/use-ai",
      icon: useAIIcon,
    });
    baseItems.push({
      label: "Upload",
      path: "/prototype/upload?type=file&scale=devider",
      icon: uploadIcon,
    });
  }

  return baseItems.map((item) => ({
    ...item,
    active: (() => {
      if (!activePath) return false;
      const basePath = item.path.split("?")[0];
      return activePath === basePath || activePath.startsWith(basePath + "/");
    })(),
  }));
};

// Creator navigation items (for backward compatibility)
export const getCreatorNavigationItems = (
  activePath?: string
): NavigationItem[] => {
  return getNavigationItems("creator", activePath);
};

// Publisher navigation items (for backward compatibility)
export const getPublisherNavigationItems = (
  activePath?: string
): NavigationItem[] => {
  return getNavigationItems("publisher", activePath);
};

